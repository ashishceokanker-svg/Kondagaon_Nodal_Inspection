export const getPanchayatsForBlock = (blockName) => {
  if (!blockName || blockName === 'सभी विकासखण्ड' || blockName === 'समस्त विकासखण्ड') {
    return Array.from(new Set(Object.values(BLOCK_PANCHAYATS).flat()));
  }
  for (const [blk, list] of Object.entries(BLOCK_PANCHAYATS)) {
    if (matchBlock(blk, blockName)) return list;
  }
  return [];
};

export const getTodayDateString = () => {
  const d = new Date();
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
};

export const getOfficerPanchayats = (officer) => {
  if (!officer) return [];
  const list = [];
  if (Array.isArray(officer.panchayats) && officer.panchayats.length > 0) {
    officer.panchayats.forEach(p => {
      if (p && typeof p === 'string') {
        p.split(',').forEach(sub => {
          const trimmed = sub.trim();
          if (trimmed && !list.includes(trimmed)) list.push(trimmed);
        });
      }
    });
  }
  if (officer.panchayat && typeof officer.panchayat === 'string') {
    officer.panchayat.split(',').forEach(sub => {
      const trimmed = sub.trim();
      if (trimmed && !list.includes(trimmed)) list.push(trimmed);
    });
  }
  return list;
};

